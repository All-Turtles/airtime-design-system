// Copies the Mask* glyph paths VERBATIM from packages/mmhmm-icons/src (React components) into assets/mask-icons.js.
// The sidebar's shape segments use these where AppIcons has no equivalent (icons.tsx: maskRectangle/Square/Circle/Hexagon).
import fs from "node:fs";
const ROOT = "/Users/dairien/workspaces/mmhmm-tv-creator-sidebar/packages/mmhmm-icons/src";
const out = {};
for (const n of ["MaskCircle", "MaskHexagon", "MaskRectangle", "MaskSquare"]) {
  const s = fs.readFileSync(`${ROOT}/${n}/${n}.tsx`, "utf8");
  out[n] = { viewBox: s.match(/viewBox="([^"]+)"/)[1], d: s.match(/\bd="([^"]+)"/)[1], fillRule: "evenodd" };
}
fs.writeFileSync(new URL("../assets/mask-icons.js", import.meta.url), `// GENERATED by tools/build-mask-icons.mjs from packages/mmhmm-icons/src/Mask*/Mask*.tsx (paths verbatim).\nvar MaskIcons = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.keys(out));
